/**
 * 战斗页的配乐 —— **谱面数据，不是音频文件**，由 `src/audio.ts` 现场合成。加一首曲子不增加任何下载。
 *
 * 四首按**页面的相位**分：塔上待机 / 寻常的战斗 / 守望者 / 营火。四首都以 **D** 为家
 * （多利亚 / 小调 / 弗里吉亚 / 大调），切歌时不会突然换调——从塔上踏进一场仗，听到的应该是
 * 同一座塔的声音变凶了，而不是另一张唱片开始了。
 *
 * ⚠️ **这个文件必须是纯数据**，`node --experimental-strip-types` 是 strip-only 的，合成器那边迟早
 * 会用上 TS 参数属性（`WorldSoundscape` 就是这么把谱面拆出去的）。这里连世界的 `Score` 类型都
 * **不 import**：本文件自成一套，所以战斗层连一个类型依赖都不欠 `src/world/**`。
 *
 * ## 为什么是「段落 + 曲式」，不是一条长表
 *
 * 两首战斗曲被要求「**三分钟以上，而且不能是单纯循环**」。一条 25 秒的表乘 8 倍还是同八小节听八遍，
 * 所以这里换了结构：一首曲子由若干**段落**（`sections`）组成，`form` 是段落名的**播放顺序**——
 * 同一段会在曲式里回来，但**回来的位置不同**，而段落之间在**音色、音量、鼓、和声**上都不一样。
 * 长度因此是 `form` 的和，不是材料的总和：`EMBERLINE` 三十二小节的材料撑出三分钟。
 *
 * 曲式里**至少要有一次「喘」**（`D`，撤掉全部鼓）——那是让下一个 `A` 打得响的东西。没有它，
 * 三分钟就是三分钟的响，而一直响等于不响。
 */

/**
 * 一件音色。和世界那套同名同义，但这里是本文件自己的声明——见文件头那条关于不 import 的说明。
 */
export interface BattleTimbre {
  pad: OscillatorType;
  lead: OscillatorType;
  harp: OscillatorType;
  /** 铺底的起音秒数：长值把和弦变成一次涌起。 */
  swell: number;
  /** 持续低音相对小节长度的比例；小于 1 留缝隙，大于 1 叠起来。 */
  pedal: number;
  /** 琶音与钟相对铺底的力度。 */
  pluck: number;
  bell: number;
  /** 混响送出量 0..1。 */
  space?: number;
  /** 延迟送出量 0..1。延迟时间由 `step` 推成**附点八分**，那是电子乐默认的呼吸长度。 */
  echo?: number;
}

/**
 * 一个段落。**可以理解成一小段独立的曲子**——它有自己的和弦、旋律、鼓、以及音色。
 *
 * `bass` / `drums` 两种写法都收：给**一行**（长度 = `steps`）就是这一段每小节都用那一行，给
 * **逐小节**的二维表就一格一格来。绝大多数段落用的是同一句 riff 反复，所以一行写法省掉大量抄写；
 * 而**需要在一段之内有变化的**（比如镲片只砸第一小节）就写逐小节。
 */
export interface Section {
  /** 一小节一个三和弦。 */
  chords: number[][];
  /** 每小节 `steps` 格 MIDI 音高，0 是空拍。**必须满格**（播放器无保护索引）。 */
  melody: number[][];
  /** 每小节 `steps` 格：取和弦的第几个音来拨，-1 是空。 */
  arpeggio: number[];
  /**
   * 低音：**相对该小节和弦根音的半音数**，`-1` 是空拍。写相对值是因为低音线九成是「同一个动作
   * 换一个和弦」，写绝对音高等于把同一个型抄十六遍。
   */
  bass?: number[] | number[][];
  /**
   * 鼓，一格一个字符：`k` 底鼓 · `s` 军鼓 · `h` 闭镲 · `o` 开镲 · `x` 拍手 · `c` 镲片 · `t` 嗵鼓
   * · `-` 空。短于 `steps` 的行按空拍补齐，所以 `''` 就是**这一小节没有鼓**。
   */
  drums?: string | string[];
  /** 第二声部（对位），和 `melody` 一样是绝对音高。允许短行，`[]` 就是这一段不进来。 */
  harmony?: number[][];
  /** 这一段覆盖掉的音色。**「更多乐器」几乎全长在这里**：同一首曲子里 A 段是方波主奏、
   *  C 段换成锯齿、D 段撤鼓换成正弦，听感上就是换了几件乐器。 */
  timbre?: Partial<BattleTimbre>;
  /** 这一段的音量倍数。段落对比靠它——**一直响等于不响**。 */
  gain?: number;
}

export interface BattleScore {
  id: string;
  name: string;
  /** 声音面板上的一行：调式、拍号、速度、以及编曲靠什么撑。 */
  note: string;
  /** 每一格的秒数。 */
  step: number;
  /** 一小节的格数。**一首曲子里所有段落共用它**，否则曲式没法摊平成一维的小节序号。 */
  steps: number;
  /** 这首曲子允许用到的音级，0 = C。写错的音会在测试里红，而不是到喇叭里才被听见。 */
  mode: number[];
  /** 段落，按名字取。 */
  sections: Record<string, Section>;
  /** 段落名的播放顺序。长度就是这首曲子的长度。 */
  form: string[];
  /** **摊平后**的小节号，在这一小节敲一次钟。 */
  bells?: number[];
  /** 这首曲子的基准音色；段落可以覆盖其中任意几项。 */
  timbre: BattleTimbre;
}

/** 低音那一轨的写法：相对根音的半音数，`-1` 是空拍。 */
const REST = -1;

/**
 * 鼓那一轨的字符表：`k` 底鼓 · `s` 军鼓 · `h` 闭镲 · `o` 开镲 · `x` 拍手 · `c` 镲片 · `t` 嗵鼓
 * · `-` 空。
 *
 * ⚠️ **`src/audio.ts` 的 `drum()` 必须对每一个字符都有分支。** 没有分支的不会报错——它会掉进
 * 兜底那段高通噪声里，听起来和闭镲 `h` 一模一样。`c` 与 `t` 就这么无声过一整轮：谱面上写着
 * 「第一小节砸镲」，响出来的只是十六分音符上的一声轻响，而**测试当时是绿的**。
 * 字符表放在这里是为了让「有哪些字符」只有一个来源；分支那一半只能靠 `drum()` 上那条注释。
 */
export const DRUM_CHARS = 'kshoxct-';

/**
 * 把曲式摊平成一串小节：`[{ section, sectionBar, bar }]`，`bar` 是整首曲子里的第几小节。
 *
 * 播放器只认这一串。抽成函数是因为它是**纯的**，而播放器不是——`audio.ts` 拉进了
 * `WorldSoundscape`，那个类的参数属性 `node --experimental-strip-types` 加载不了。
 * 于是「曲式接得对不对、总长是多少」就只能在这里被验证。
 */
export function barsOf(score: BattleScore): { section: Section; sectionBar: number; bar: number }[] {
  const out: { section: Section; sectionBar: number; bar: number }[] = [];
  for (const name of score.form) {
    const section = score.sections[name];
    if (!section) continue;
    section.chords.forEach((_, index) => out.push({ section, sectionBar: index, bar: out.length }));
  }
  return out;
}

/** 一整首有多少小节。 */
export function totalBars(score: BattleScore): number {
  return barsOf(score).length;
}

/**
 * 段落里某一小节的**低音行**——`bass` 的两种写法（一行 / 逐小节）在这里归一。
 *
 * 归一放在这里而不是播放器里，理由和 `barsOf` 一样：播放器测不到，纯函数测得到。而「一行写法
 * 被当成了逐小节表」这种错在播放器里的表现是整段低音消失，耳朵不一定当场分辨得出。
 */
export function bassRow(section: Section, bar: number): number[] | undefined {
  const bass = section.bass;
  if (!bass) return undefined;
  return typeof bass[0] === 'number' ? (bass as number[]) : (bass as number[][])[bar];
}

/** 段落里某一小节的**鼓行**。`''` 与 `undefined` 都表示这一小节没有鼓。 */
export function drumRow(section: Section, bar: number): string | undefined {
  const drums = section.drums;
  if (drums === undefined) return undefined;
  return typeof drums === 'string' ? drums : drums[bar];
}

/** 一整首有多少格。`tick % totalTicks` 决定现在落在哪一小节。 */
export function loopTicks(score: BattleScore): number {
  return totalBars(score) * score.steps;
}

/** 一整首有多少秒——「这一首大概多长」的答案，测试拿它对账。 */
export function loopSeconds(score: BattleScore): number {
  return loopTicks(score) * score.step;
}

